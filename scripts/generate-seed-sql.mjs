// Generates supabase/migrations/20260917120200_seed_live_site_content.sql from
// the app's bundled seed data, so the database, the app's fallback, and the
// website (which shares the same tables) agree on one source of truth.
//
//   node scripts/generate-seed-sql.mjs
//
// Requires Node 22.6+ (native TypeScript type-stripping for the .ts imports).
// Idempotent SQL: every insert is `on conflict do nothing` or guarded by
// `not exists`, and org_id is looked up by name at apply time.
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

const load = (rel) => import(pathToFileURL(join(root, rel)).href)
const { seedEvents } = await load('src/data/events.ts')
const { seedVets } = await load('src/data/vets.ts')
const { seedCareArticles } = await load('src/data/careArticles.ts')
const { volunteerWays } = await load('src/data/volunteer.ts')
const { seedHeroSlides } = await load('src/data/heroSlides.ts')

const q = (v) => {
  if (v === undefined || v === null || v === '') return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

const out = []
out.push(`-- =============================================================
-- OHRR App + Website — Seed: live-site content (captured 2026-09-17)
--
-- GENERATED by scripts/generate-seed-sql.mjs from src/data/{events,vets,
-- careArticles,volunteer}.ts — edit those files and re-run, don't hand-edit.
--
-- Seeds, for the 'Ohio House Rabbit Rescue' organization:
--   * events:                  Midwest BunFest 2026 (${seedEvents.length} row)
--   * vets:                    the rabbit-savvy vet directory (${seedVets.length} rows)
--   * care_articles:           the ${seedCareArticles.length} Resources articles + Living Space + Stray
--   * volunteer_opportunities: the ${volunteerWays.length} volunteer positions
--   * hero_slides:             ${seedHeroSlides.length} hero / featured slides (image_url null)
--
-- Apply AFTER *_events.sql, *_vets.sql and *_hero_slides.sql (and the earlier care_articles /
-- volunteer_opportunities migrations). Idempotent: re-running inserts nothing
-- new; existing rows are never overwritten (staff edits are preserved).
-- =============================================================

do $$
declare
  v_org uuid;
begin
  select id into v_org from organizations where name = 'Ohio House Rabbit Rescue' limit 1;
  if v_org is null then
    raise exception 'Organization "Ohio House Rabbit Rescue" not found — apply the hopshop backend migration first.';
  end if;
`)

out.push(`\n  -- ---- events ----`)
seedEvents.forEach((e, i) => {
  out.push(`  insert into events (org_id, slug, title, starts_at, ends_at, venue, address, city, summary, body, theme, url, is_published, sort_order)
  values (v_org, ${q(e.slug)}, ${q(e.title)}, ${q(e.startsAt)}, ${q(e.endsAt)}, ${q(e.venue)}, ${q(e.address)}, ${q(e.city)}, ${q(e.summary)}, ${q(e.body)}, ${q(e.theme)}, ${q(e.url)}, true, ${i})
  on conflict (org_id, slug) do nothing;`)
})

out.push(`\n  -- ---- vets ----`)
seedVets.forEach((v, i) => {
  out.push(`  insert into vets (org_id, name, doctors, address, city, region, phone, phone2, email, website, notes, is_emergency, is_low_cost_spay, is_published, sort_order)
  select v_org, ${q(v.name)}, ${q(v.doctors)}, ${q(v.address)}, ${q(v.city)}, ${q(v.region)}, ${q(v.phone)}, ${q(v.phone2)}, ${q(v.email)}, ${q(v.website)}, ${q(v.notes)}, ${q(v.isEmergency)}, ${q(v.isLowCostSpay)}, true, ${i}
  where not exists (select 1 from vets where org_id = v_org and name = ${q(v.name)});`)
})

out.push(`\n  -- ---- care_articles ----`)
seedCareArticles.forEach((a) => {
  out.push(`  insert into care_articles (org_id, slug, title, icon, summary, body, tip, sort_order, is_published)
  values (v_org, ${q(a.slug)}, ${q(a.title)}, ${q(a.icon)}, ${q(a.summary)}, ${q(a.body)}, ${q(a.tip)}, ${a.sort_order}, true)
  on conflict (org_id, slug) do nothing;`)
})

out.push(`\n  -- ---- volunteer_opportunities (one row per real position) ----`)
volunteerWays.forEach((w, i) => {
  const detail = [w.summary, '', 'Requirements:', ...w.requirements.map((r) => `- ${r}`)].join('\n')
  out.push(`  insert into volunteer_opportunities (org_id, category, title, detail, when_text, where_text, spots, is_published, sort_order)
  select v_org, ${q(w.slug)}, ${q(w.title)}, ${q(detail)}, ${q(w.commitment)}, ${q(w.location)}, null, true, ${i}
  where not exists (select 1 from volunteer_opportunities where org_id = v_org and category = ${q(w.slug)} and title = ${q(w.title)});`)
})

out.push(`\n  -- ---- hero_slides (image_url left null; the site/app use bundled photos) ----`)
seedHeroSlides.forEach((h) => {
  out.push(`  insert into hero_slides (org_id, placement, headline, subline, image_url, cta_label, cta_url, starts_at, ends_at, is_published, sort_order)
  select v_org, ${q(h.placement)}, ${q(h.headline)}, ${q(h.subline)}, null, ${q(h.ctaLabel)}, ${q(h.ctaUrl)}, ${q(h.startsAt)}, ${q(h.endsAt)}, true, ${h.sortOrder}
  where not exists (select 1 from hero_slides where org_id = v_org and placement = ${q(h.placement)} and headline = ${q(h.headline)});`)
})

out.push(`end $$;\n`)

const target = join(root, 'supabase/migrations/20260917120200_seed_live_site_content.sql')
writeFileSync(target, out.join('\n'), 'utf8')
console.log(`wrote ${target}`)
